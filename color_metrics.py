def _self_test():
    """Sharma 2005 官方测试集验证：34对全部通过（误差<1e-3）才可用于实验"""
    max_err = 0.0
    n_pass = 0
    for i, (l1, l2, exp) in enumerate(SHARMA_TEST, 1):
        got = float(ciede2000_std(np.array([l1]), np.array([l2]))[0])
        err = abs(got - exp)
        max_err = max(max_err, err)
        if err < 1e-3:
            n_pass += 1
        else:
            print(f"  对{i}: 得到{got:.4f} 期望{exp:.4f} ✗")
    print(f"CIEDE2000 标准实现自验证: {n_pass}/34 通过, 最大误差 {max_err:.2e}")
    return n_pass == 34


