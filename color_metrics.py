"""
颜色度量模块：标准 CIEDE2000 + sRGB→Lab(D65) 转换
====================================================
- ciede2000_std: 标准 CIEDE2000 色差（CIE 2000 / Sharma et al. 2005 公式），
  向量化实现，经 Sharma 2005 官方 34 对补充测试数据自验证（见 _self_test）。
- rgb_to_lab: sRGB 显示域 → Lab(D65)。
所有实验指标统一从本模块引用，不再使用简化公式。
"""
import numpy as np


def rgb_to_lab(img):
    """RGB[0,1] → Lab（D65白点，sRGB标准变换）"""
    img = img.astype(np.float64)
    lin = np.where(img <= 0.04045, img / 12.92, ((img + 0.055) / 1.055) ** 2.4)
    M = np.array([[0.4124564, 0.3575761, 0.1804375],
                  [0.2126729, 0.7151522, 0.0721750],
                  [0.0193339, 0.1191920, 0.9503041]])
    xyz = lin @ M.T
    wp = np.array([0.95047, 1.0, 1.08883])
    t = xyz / wp
    t = np.where(t > 0.008856, np.cbrt(t), t / 0.008856 * 7.787 + 16 / 116)
    L = 116 * t[..., 1] - 16
    a = 500 * (t[..., 0] - t[..., 1])
    bb = 200 * (t[..., 1] - t[..., 2])
    return np.stack([L, a, bb], axis=-1)


def ciede2000_std(lab1, lab2, kL=1.0, kC=1.0, kH=1.0):
    """
    标准 CIEDE2000 色差（Sharma et al. 2005 完整公式，含 G 修正、
    色相差 wraparound、hue 均值三分支、T 项、RT 旋转项）。
    lab1/lab2: shape (..., 3) 的 Lab 数组，逐元素计算后返回同形状 dE00。
    """
    L1, a1, b1 = lab1[..., 0], lab1[..., 1], lab1[..., 2]
    L2, a2, b2 = lab2[..., 0], lab2[..., 1], lab2[..., 2]

    C1 = np.sqrt(a1 ** 2 + b1 ** 2)
    C2 = np.sqrt(a2 ** 2 + b2 ** 2)
    Cbar = (C1 + C2) / 2.0
    Cbar7 = Cbar ** 7
    G = 0.5 * (1.0 - np.sqrt(Cbar7 / (Cbar7 + 25.0 ** 7)))
    a1p = (1.0 + G) * a1
    a2p = (1.0 + G) * a2
    C1p = np.sqrt(a1p ** 2 + b1 ** 2)
    C2p = np.sqrt(a2p ** 2 + b2 ** 2)
    h1p = np.degrees(np.arctan2(b1, a1p)) % 360.0
    h2p = np.degrees(np.arctan2(b2, a2p)) % 360.0

    dLp = L2 - L1
    dCp = C2p - C1p

    # 色相差 dhp（wraparound；C1p*C2p=0 时为 0）
    zeroC = (C1p * C2p) == 0
    dhp = h2p - h1p
    dhp = np.where(dhp > 180.0, dhp - 360.0, dhp)
    dhp = np.where(dhp < -180.0, dhp + 360.0, dhp)
    dhp = np.where(zeroC, 0.0, dhp)
    dHp = 2.0 * np.sqrt(C1p * C2p) * np.sin(np.radians(dhp / 2.0))

    Lbp = (L1 + L2) / 2.0
    Cbp = (C1p + C2p) / 2.0

    # 色相均值 hbp（三分支；C1p*C2p=0 时取和，该情形 dHp=0 不影响结果）
    hsum = h1p + h2p
    dabsh = np.abs(h1p - h2p)
    hbp = np.where(dabsh <= 180.0, hsum / 2.0,
                   np.where(hsum < 360.0, (hsum + 360.0) / 2.0, (hsum - 360.0) / 2.0))
    hbp = np.where(zeroC, hsum, hbp)

    T = (1.0 - 0.17 * np.cos(np.radians(hbp - 30.0))
         + 0.24 * np.cos(np.radians(2.0 * hbp))
         + 0.32 * np.cos(np.radians(3.0 * hbp + 6.0))
         - 0.20 * np.cos(np.radians(4.0 * hbp - 63.0)))
    dtheta = 30.0 * np.exp(-(((hbp - 275.0) / 25.0) ** 2))
    Cbp7 = Cbp ** 7
    RC = 2.0 * np.sqrt(Cbp7 / (Cbp7 + 25.0 ** 7))
    SL = 1.0 + (0.015 * (Lbp - 50.0) ** 2) / np.sqrt(20.0 + (Lbp - 50.0) ** 2)
    SC = 1.0 + 0.045 * Cbp
    SH = 1.0 + 0.015 * Cbp * T
    RT = -np.sin(np.radians(2.0 * dtheta)) * RC

    tL = dLp / (kL * SL)
    tC = dCp / (kC * SC)
    tH = dHp / (kH * SH)
    dE = np.sqrt(tL ** 2 + tC ** 2 + tH ** 2 + RT * tC * tH)
    return dE


